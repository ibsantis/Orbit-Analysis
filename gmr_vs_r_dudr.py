"""
    Calculate what GM/R is from the enclosed mass data
"""
def gmr(mass, dist):
    array = np.zeros(len(mass))
    for i in range(0,len(dist)):
        array[i] = ((6.67*10**(-11)*2*10**(30))/(10**3*3.086*10**(16)*1000**2))*mass[i]/dist[i]
    return array

