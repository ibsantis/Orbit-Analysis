    array = np.zeros(int(len(pot)/2))
    inds = np.arange(0, len(pot), 2)
    for i in inds:
        array[int(i/2)] = dist[i+1]*2*(pot[i+1]-pot[i])/10 # extra factor of two to account for the incorrect h^2 correction
    return array

